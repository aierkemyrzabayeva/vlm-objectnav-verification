#!/usr/bin/env python3
"""
make_env_ours.py - create ours/real_env_ours.py from the authors' TD3/real_env_dd.py.

The authors' file is never modified. Four minimal, documented patches are applied and every
patch must match the expected number of times, otherwise nothing is written.

  1. killall loop disabled      two jobs of one user on one node must not kill each other's Gazebo
  2. ROS port from env          ROS_PORT_SIM (default 11311), so parallel jobs use different ports
  3. screenshots disabled       take_screenshot() needs an overhead camera that our worlds lack
  4. forced start pose          env.forced_start = (x, y, yaw) is used by reset() instead of random start
  5. simulation-time stepping   each step waits for TIME_DELTA seconds of SIMULATION time (from /clock)
                                instead of wall-clock time, so the dynamics do not depend on the real-time
                                factor of the machine (RTF was 0.65-1.0 on the cluster)

Usage (from the `ours` directory):
    python3 make_env_ours.py ../TD3/real_env_dd.py real_env_ours.py
"""
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "../TD3/real_env_dd.py"
DST = sys.argv[2] if len(sys.argv) > 2 else "real_env_ours.py"

src = open(SRC).read()
report = []


def apply_plain(text, name, old, new, expected):
    n = text.count(old)
    report.append((name, n, expected))
    return text.replace(old, new)


def apply_regex(text, name, pattern, repl, expected, count=0):
    new, n = re.subn(pattern, repl, text, count=count)
    report.append((name, n, expected))
    return new


src = apply_plain(
    src, "killall loop disabled",
    'for proc in ["roscore", "rosmaster", "gzserver", "gzclient", "rtabmap"]:',
    'for proc in []:  # [ours] do not kill processes of parallel jobs', 1)

src = apply_plain(
    src, "ros port from env",
    'port = "11311"',
    'port = os.environ.get("ROS_PORT_SIM", "11311")  # [ours]', 1)

src = apply_plain(
    src, "screenshots disabled",
    'self.take_screenshot()',
    'None  # [ours] screenshot disabled (no overhead camera)', None)   # any number >= 1

start_pat = (r"([ ]*)while not x_ok:[ \t]*\n[ \t]*x = np\.random\.uniform\(-9, 9\)[ \t]*\n"
             r"[ \t]*y = np\.random\.uniform\(-3, 2\)[ \t]*\n[ \t]*x_ok = self\.check_pos\(x, y\)")
start_new = (r"\1_fs = getattr(self, 'forced_start', None)  # [ours] (x, y, yaw) or None\n"
             r"\1if _fs is not None:\n"
             r"\1    x, y, angle = _fs\n"
             r"\1    quat = Quaternion.from_euler(0, 0, angle)\n"
             r"\1    x_ok = True\n"
             r"\1while not x_ok:\n"
             r"\1    x = np.random.uniform(-9, 9)\n"
             r"\1    y = np.random.uniform(-3, 2)\n"
             r"\1    x_ok = self.check_pos(x, y)")
src = apply_regex(src, "forced start pose", start_pat, start_new, 1)

src = apply_plain(
    src, "sleep(TIME_DELTA) -> sim wait",
    'time.sleep(TIME_DELTA)',
    'self._sim_wait(TIME_DELTA)  # [ours]', None)

src = apply_regex(
    src, "import Clock",
    r"(?m)^import rospy[ \t]*$",
    "import rospy\nfrom rosgraph_msgs.msg import Clock  # [ours]", 1, count=1)

src = apply_regex(
    src, "clock subscriber",
    r'(?m)^([ ]+)(self\.reset_proxy = rospy\.ServiceProxy\("/gazebo/reset_world", Empty\))[ \t]*$',
    r'\1\2\n\1self._sim_t = None  # [ours]\n\1rospy.Subscriber("/clock", Clock, self._clock_cb, queue_size=1)  # [ours]', 1)

sim_methods = (
    "    def _clock_cb(self, msg):  # [ours]\n"
    "        self._sim_t = msg.clock.to_sec()\n\n"
    "    def _sim_wait(self, dt, wall_timeout=3.0):  # [ours] wait until dt seconds of SIMULATION time passed\n"
    "        t_wall = time.time()\n"
    "        t0 = self._sim_t\n"
    "        if t0 is None:\n"
    "            time.sleep(dt)\n"
    "            return\n"
    "        while (self._sim_t - t0) < dt and (time.time() - t_wall) < wall_timeout:\n"
    "            time.sleep(0.002)\n\n"
)
src = apply_regex(
    src, "sim wait methods",
    r"(?m)^    def step\(self, action\):",
    lambda m: sim_methods + m.group(0), 1)

ok = True
for name, n, expected in report:
    good = (n >= 1) if expected is None else (n == expected)
    ok &= good
    print(f"{'OK  ' if good else 'FAIL'} {name}: matched {n} time(s)" +
          ("" if expected is None else f" (expected {expected})"))
if not ok:
    sys.exit("At least one patch did not match; nothing was written. Send this output to the assistant.")

header = ("# AUTO-GENERATED by make_env_ours.py from real_env_dd.py - do not edit by hand.\n"
          "# Patches: killall disabled, ROS port from ROS_PORT_SIM, screenshots disabled, forced_start.\n")
open(DST, "w").write(header + src)
print(f"written {DST}")
